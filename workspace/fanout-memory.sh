#!/bin/bash
#
# fanout-memory.sh — fan out universal memories from the workspace hub to each subproject
#
# Claude Code keeps per-folder memory at ~/.claude/projects/<slug>/memory/, where <slug> is
# the folder's absolute path with every "/" replaced by "-". The workspace root's memory dir
# is the HUB. Universal memory files (feedback_*.md and user_*.md) live ONLY in the hub; every
# subproject's memory dir gets a symlink back to each one. Edit a universal file once and
# every project sees the change.
#
# project_*.md and reference_*.md files are NOT fanned out — they stay where they are.
#
# The MEMORY.md index is REBUILT on every run, not appended to. Claude Code loads only the
# first 200 lines / 25,000 characters of a MEMORY.md and silently drops the rest from the
# bottom, so a long list of shared lines pushes a project's own notes out of view. Each index
# is written as:
#   ## Always first (shared, pinned)   universals with `pinned: true`, + a pointer to the full list
#   ## This project                    every other line already in the index, kept verbatim
#   ## Shared notes (generated …)      the other universals, one short line each
# A universal's index line is its `hook:` frontmatter line (90 characters max; the rule in a
# phrase), or its description cut to 90 characters when it has no hook. Never hand-edit the
# generated lines — edit the note's hook and re-run. The hub also gets SHARED-NOTES.md: every
# universal with its full description, the fallback when an index is cut off.
#
# Usage:
#   fanout-memory.sh                  Status: which subprojects are missing which universals
#   fanout-memory.sh <project-name>   Seed/sync one subproject (creates its memory dir if needed)
#   fanout-memory.sh --all            Sync every existing subproject and the hub's own index
#   fanout-memory.sh --check [name]   Report index sizes, write nothing; exit 1 when any is
#                                     over 22,000 characters or 180 lines (limit: 25,000 / 200)
#
# Configuration: honours $WORKSPACE_DIR (default ~/CLAUDE).

set -euo pipefail

WORKSPACE_DIR="${WORKSPACE_DIR:-$HOME/CLAUDE}"
WORKSPACE_DIR="${WORKSPACE_DIR/#\~/$HOME}"
WORKSPACE_DIR="${WORKSPACE_DIR%/}"
HUB_SLUG="$(printf '%s' "$WORKSPACE_DIR" | tr '/' '-')"
PROJECTS_BASE="$HOME/.claude/projects"
HUB_MEMORY="$PROJECTS_BASE/$HUB_SLUG/memory"
SUBPROJECT_PREFIX="${HUB_SLUG}-"
FULL_LIST="$HUB_MEMORY/SHARED-NOTES.md"

# Claude Code's own MEMORY.md limits, and the earlier point where this script warns.
LIMIT_LINES=200; LIMIT_CHARS=25000
WARN_LINES=180;  WARN_CHARS=22000
HOOK_MAX=90

H_PINNED="## Always first (shared, pinned)"
H_PROJECT="## This project"
H_SHARED="## Shared notes (generated by fanout-memory.sh from each note's \`hook:\` — edit the note, not these lines)"
POINTER_TEXT="Full list of every shared note, with full descriptions"

if [ "${1:-}" = "--help" ] || [ "${1:-}" = "-h" ]; then
  sed -n '/^# fanout-memory.sh/,/^$/p' "$0" | sed -E 's/^# ?//'
  exit 0
fi

# ── Size check ────────────────────────────────────────────────────────────────────────────
WORST=0
report_size() {  # report_size <memory dir> <label>
  local index="$1/MEMORY.md" label="$2" chars lines flag
  [ -f "$index" ] || return 0
  chars=$(wc -m < "$index" | tr -d ' ')
  lines=$(wc -l < "$index" | tr -d ' ')
  if [ "$chars" -gt "$LIMIT_CHARS" ] || [ "$lines" -gt "$LIMIT_LINES" ]; then
    flag="OVER LIMIT — the bottom of this index is not loading"; WORST=2
  elif [ "$chars" -gt "$WARN_CHARS" ] || [ "$lines" -gt "$WARN_LINES" ]; then
    flag="WARNING — near the limit"; [ "$WORST" -ge 1 ] || WORST=1
  else
    flag="ok"
  fi
  printf '  %6s chars %4s lines  %s  %s\n' "$chars" "$lines" "$flag" "$label"
}
size_advice() {
  [ "$WORST" -eq 0 ] && return 0
  echo "Claude Code reads only the first $LIMIT_LINES lines / $LIMIT_CHARS characters of MEMORY.md."
  echo "Fix: shorten long index lines (and universals' hook: lines), unpin notes, or move detail"
  echo "out of index lines into the memory files themselves."
}

if [ "${1:-}" = "--check" ]; then
  if [ -n "${2:-}" ]; then
    report_size "$PROJECTS_BASE/${SUBPROJECT_PREFIX}$2/memory" "$2"
  else
    report_size "$HUB_MEMORY" "(hub)"
    for d in "$PROJECTS_BASE/${SUBPROJECT_PREFIX}"*; do
      [ -d "$d/memory" ] || continue
      report_size "$d/memory" "$(basename -- "$d" | sed "s|^${SUBPROJECT_PREFIX}||")"
    done
  fi
  size_advice
  [ "$WORST" -eq 0 ]
  exit $?
fi

mkdir -p "$HUB_MEMORY"

# Build the list of universal memory filenames from the hub
universal_files=()
for f in "$HUB_MEMORY"/feedback_*.md "$HUB_MEMORY"/user_*.md; do
  [ -e "$f" ] || continue
  universal_files+=("$(basename "$f")")
done

if [ "${#universal_files[@]}" -eq 0 ]; then
  echo "No universal memory files (feedback_*.md / user_*.md) in $HUB_MEMORY yet." >&2
  echo "Write one there first (user_profile.md is the usual starting point), then re-run." >&2
  echo "If that path is not what you expected, check \$WORKSPACE_DIR (currently: $WORKSPACE_DIR)." >&2
  exit 1
fi

# Read one frontmatter field (unquoted, \" unescaped)
fm_field() {  # fm_field <file> <key>
  local v
  v="$(awk -v k="$2" 'NR==1 && $0!="---" {exit} NR>1 && $0=="---" {exit}
       index($0, k": ")==1 {print substr($0, length(k)+3); exit}' "$1")"
  v="${v%\"}"; v="${v#\"}"
  printf '%s' "${v//\\\"/\"}"
}

# One generated index line per universal, computed once
hooks=(); pinned=(); descs=()
for filename in "${universal_files[@]}"; do
  f="$HUB_MEMORY/$filename"
  desc="$(fm_field "$f" description)"
  hook="$(fm_field "$f" hook)"
  if [ -z "$hook" ]; then
    hook="$desc"
    if [ "${#hook}" -gt "$HOOK_MAX" ]; then
      hook="${hook:0:$HOOK_MAX}"; hook="${hook% *}…"
    fi
  fi
  hook="${hook//\[/(}"; hook="${hook//\]/)}"
  hooks+=("$hook")
  descs+=("$desc")
  if [ "$(fm_field "$f" pinned)" = "true" ]; then pinned+=(1); else pinned+=(0); fi
done

# Rebuild one MEMORY.md. In a subproject, a universal it holds as a REAL file (its own copy)
# is that project's line, not a generated one.
rebuild_index() {  # rebuild_index <memory dir> <is_hub 0|1>
  local memdir="$1" is_hub="$2" index="$1/MEMORY.md"
  local managed="|" i filename line base own=() tmp link_re='[]][(]([^)]+[.]md)[)]'
  for i in "${!universal_files[@]}"; do
    filename="${universal_files[$i]}"
    if [ "$is_hub" = 1 ] || [ -L "$memdir/$filename" ]; then managed="$managed$filename|"; fi
  done

  if [ -f "$index" ]; then
    while IFS= read -r line || [ -n "$line" ]; do
      base=""
      if [[ "$line" =~ $link_re ]]; then base="$(basename -- "${BASH_REMATCH[1]}")"; fi
      if [ -n "$base" ] && [[ "$managed" == *"|$base|"* ]]; then continue; fi
      case "$line" in
        "# Memory index"*|"## Always first"*|"$H_PROJECT"|"## Shared notes"*|"- [$POINTER_TEXT]"*|"(no project-specific notes yet"*) continue ;;
      esac
      # collapse runs of blank lines
      if [ -z "$line" ] && { [ "${#own[@]}" -eq 0 ] || [ -z "${own[${#own[@]}-1]}" ]; }; then continue; fi
      own+=("$line")
    done < "$index"
  fi
  while [ "${#own[@]}" -gt 0 ] && [ -z "${own[${#own[@]}-1]}" ]; do unset 'own[${#own[@]}-1]'; done

  tmp="$index.tmp.$$"
  {
    echo "# Memory index"; echo ""; echo "$H_PINNED"
    for i in "${!universal_files[@]}"; do
      filename="${universal_files[$i]}"
      [[ "$managed" == *"|$filename|"* ]] && [ "${pinned[$i]}" = 1 ] && echo "- [${hooks[$i]}]($filename)"
    done
    echo "- [$POINTER_TEXT]($FULL_LIST) — read it if nothing here fits or this index looks cut off"
    echo ""; echo "$H_PROJECT"
    if [ "${#own[@]}" -gt 0 ]; then
      printf '%s\n' "${own[@]}"
    else
      echo "(no project-specific notes yet — add them here, above the shared list)"
    fi
    echo ""; echo "$H_SHARED"
    for i in "${!universal_files[@]}"; do
      filename="${universal_files[$i]}"
      [[ "$managed" == *"|$filename|"* ]] && [ "${pinned[$i]}" = 0 ] && echo "- [${hooks[$i]}]($filename)"
    done
    true
  } > "$tmp"
  if [ -f "$index" ] && cmp -s "$tmp" "$index"; then rm -f "$tmp"; return 0; fi
  [ -f "$index" ] && echo "    ↻ MEMORY.md rebuilt" || echo "    + MEMORY.md"
  mv "$tmp" "$index"
}

write_full_list() {
  local i tmp="$FULL_LIST.tmp.$$" star
  {
    echo "# Every shared memory note"; echo ""
    echo "Generated by fanout-memory.sh — the fallback for MEMORY.md: if an index looks cut off or"
    echo "nothing in it fits, scan this list. Each note lives in this folder and is symlinked into"
    echo "every project's memory folder. Pinned notes are marked ★."; echo ""
    for i in "${!universal_files[@]}"; do
      star=""; [ "${pinned[$i]}" = 1 ] && star="★ "
      echo "- ${star}[${universal_files[$i]}](${universal_files[$i]}) — ${descs[$i]:-${hooks[$i]}}"
    done
  } > "$tmp"
  mv "$tmp" "$FULL_LIST"
}

# Sync universal memories into one subproject's memory dir
fanout_one() {
  local project_name="$1"
  local project_memory="$PROJECTS_BASE/${SUBPROJECT_PREFIX}${project_name}/memory"

  echo "▸ $project_name"
  mkdir -p "$project_memory"

  local linked_count=0
  for filename in "${universal_files[@]}"; do
    local target="$project_memory/$filename"
    local src="$HUB_MEMORY/$filename"
    if [ -L "$target" ] && [ "$(readlink "$target")" = "$src" ]; then
      continue
    fi
    if [ -e "$target" ] && [ ! -L "$target" ]; then
      echo "    ! $filename exists here as a real file — skipping (move or rename it to fan out)"
      continue
    fi
    ln -sf "$src" "$target"
    linked_count=$((linked_count + 1))
    echo "    + $filename"
  done

  if [ "$linked_count" -eq 0 ]; then
    echo "    (symlinks already current)"
  fi

  rebuild_index "$project_memory" 0
}

# Status report: which subprojects are missing which universals
show_status() {
  echo "Workspace: $WORKSPACE_DIR"
  echo "Hub:       $HUB_MEMORY"
  echo "Universal memories (${#universal_files[@]}):"
  for filename in "${universal_files[@]}"; do
    echo "  • $filename"
  done
  echo ""
  echo "Subproject status:"
  local found_any=0
  for d in "$PROJECTS_BASE/${SUBPROJECT_PREFIX}"*; do
    [ -d "$d" ] || continue
    found_any=1
    local project
    project="$(basename -- "$d" | sed "s|^${SUBPROJECT_PREFIX}||")"
    local project_memory="$d/memory"
    local missing=0
    for filename in "${universal_files[@]}"; do
      if [ ! -L "$project_memory/$filename" ]; then
        missing=$((missing + 1))
      fi
    done
    if [ "$missing" -eq 0 ]; then
      echo "  ✓ $project"
    else
      echo "  ⚠ $project — missing $missing universal symlink(s)"
    fi
  done
  if [ "$found_any" -eq 0 ]; then
    echo "  (no subprojects yet — /newproject <name> creates the first one)"
  fi
  echo ""
  echo "Run:"
  echo "  $0 <project-name>    Seed/sync one project"
  echo "  $0 --all             Sync every subproject"
  echo "  $0 --check           Report MEMORY.md sizes"
}

case "${1:-}" in
  "")
    show_status
    ;;
  --all)
    echo "▸ (hub)"
    rebuild_index "$HUB_MEMORY" 1
    for d in "$PROJECTS_BASE/${SUBPROJECT_PREFIX}"*; do
      [ -d "$d" ] || continue
      project="$(basename -- "$d" | sed "s|^${SUBPROJECT_PREFIX}||")"
      fanout_one "$project"
    done
    write_full_list
    echo ""
    echo "Index sizes:"
    report_size "$HUB_MEMORY" "(hub)"
    for d in "$PROJECTS_BASE/${SUBPROJECT_PREFIX}"*; do
      [ -d "$d/memory" ] || continue
      report_size "$d/memory" "$(basename -- "$d" | sed "s|^${SUBPROJECT_PREFIX}||")"
    done
    size_advice
    echo ""
    echo "Done."
    ;;
  *)
    fanout_one "$1"
    write_full_list
    echo ""
    report_size "$PROJECTS_BASE/${SUBPROJECT_PREFIX}$1/memory" "$1"
    size_advice
    echo ""
    echo "Done."
    ;;
esac
